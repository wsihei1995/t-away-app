-- Safe customer tracking: this table contains no address, phone or payment data.
-- Customers can subscribe to a random order UUID and only receive status changes.
create table if not exists public.order_tracking (
  order_id uuid primary key references public.orders(id) on delete cascade,
  public_code text not null,
  status text not null check (status in ('pending','confirmed','preparing','delivering','completed','cancelled')),
  updated_at timestamptz not null default now()
);

alter table public.order_tracking enable row level security;

drop policy if exists "Public can read order tracking" on public.order_tracking;
create policy "Public can read order tracking" on public.order_tracking
for select to anon, authenticated using (true);

drop policy if exists "Authenticated admins can manage order tracking" on public.order_tracking;
create policy "Authenticated admins can manage order tracking" on public.order_tracking
for all to authenticated using (true) with check (true);

create or replace function public.sync_order_tracking()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.order_tracking(order_id, public_code, status, updated_at)
  values (new.id, new.public_code, new.status, new.updated_at)
  on conflict (order_id) do update set
    public_code = excluded.public_code,
    status = excluded.status,
    updated_at = excluded.updated_at;
  return new;
end;
$$;

drop trigger if exists orders_sync_tracking on public.orders;
create trigger orders_sync_tracking
after insert or update of status, public_code, updated_at on public.orders
for each row execute procedure public.sync_order_tracking();

-- Backfill orders that existed before this migration was run.
insert into public.order_tracking(order_id, public_code, status, updated_at)
select id, public_code, status, updated_at from public.orders
on conflict (order_id) do update set
  public_code = excluded.public_code,
  status = excluded.status,
  updated_at = excluded.updated_at;

-- Realtime is required for the customer app to receive status updates.
do $$
begin
  alter publication supabase_realtime add table public.order_tracking;
exception when duplicate_object then
  null;
end;
$$;
