-- T-AWAY Supabase cloud database schema
-- Run this once in Supabase Dashboard > SQL Editor > New query.

create extension if not exists pgcrypto;

create table if not exists public.restaurants (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null default '飯類',
  area text,
  delivery_time text default '20–30 分鐘',
  delivery_fee_label text default '$8 起',
  rating numeric(2,1) default 5.0,
  review_count integer default 0,
  cover text default 'green',
  emoji text default '🍽️',
  label text default '街坊推介',
  tags jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  restaurant_id bigint not null references public.restaurants(id) on delete cascade,
  name text not null,
  description text,
  price numeric(10,2) not null default 0,
  emoji text default '🍽️',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.menu_items
  add column if not exists category text not null default '其他';

-- Give existing menu items a useful initial category; admins can edit these later.
update public.menu_items m
set category = case
  when m.name ~ '(茶|奶茶|飲|檸|珍珠|烏龍|冬瓜)' then '飲品'
  when m.name ~ '(麵|粉|米線)' then '麵食'
  when m.name ~ '(飯|便當|丼)' then '飯類'
  when m.name ~ '(布丁|奶酪|甜|楊枝|蛋糕)' then '甜品'
  when m.name ~ '(雞翼|香腸|燒賣|魚蛋|小食)' then '小食'
  when r.category = '茶飲' then '飲品'
  else coalesce(r.category, '其他')
end
from public.restaurants r
where m.restaurant_id = r.id
  and m.category = '其他';

create table if not exists public.payment_settings (
  id text primary key default 'default',
  alipay_qr_url text,
  wechat_qr_url text,
  fps_phone text,
  account_name text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

alter table public.payment_settings enable row level security;

drop policy if exists "Public can read active payment settings" on public.payment_settings;
create policy "Public can read active payment settings" on public.payment_settings
for select to anon, authenticated using (active = true);

drop policy if exists "Authenticated admins can manage payment settings" on public.payment_settings;
create policy "Authenticated admins can manage payment settings" on public.payment_settings
for all to authenticated using (true) with check (true);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  public_code text not null unique,
  customer_id uuid references auth.users(id) on delete set null,
  status text not null default 'pending' check (status in ('pending','confirmed','preparing','delivering','completed','cancelled')),
  payment_method text,
  address text not null,
  phone text not null,
  note text,
  subtotal numeric(10,2) not null default 0,
  delivery_fee numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  restaurant_id bigint,
  restaurant_name text,
  item_name text not null,
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(10,2) not null default 0,
  created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

